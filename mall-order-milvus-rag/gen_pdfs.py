# -*- coding: utf-8 -*-
"""Generate 7 Chinese PDF documents for RAG knowledge base."""
from fpdf import FPDF
import os

OUTPUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                          "src/main/resources/data")
FONT_PATH = "/System/Library/Fonts/STHeiti Medium.ttc"
os.makedirs(OUTPUT_DIR, exist_ok=True)


class ChinesePDF(FPDF):
    def __init__(self, title):
        super().__init__()
        self.add_font("CN", fname=FONT_PATH)
        self.add_page()
        self.doc_title = title
        self.set_auto_page_break(True, 15)
        self._header()

    def _header(self):
        self.set_font("CN", size=9)
        self.set_text_color(128)
        self.cell(0, 8, self.doc_title, align="C",
                  new_x="LMARGIN", new_y="NEXT")
        self.line(self.l_margin, self.get_y(),
                  self.w - self.r_margin, self.get_y())
        self.ln(4)

    def cover_title(self, text):
        self.set_font("CN", size=22)
        self.set_text_color(0)
        self.cell(0, 14, text, align="C",
                  new_x="LMARGIN", new_y="NEXT")
        self.ln(6)

    def subtitle(self, text):
        self.set_font("CN", size=11)
        self.set_text_color(80)
        self.cell(0, 8, text, align="C",
                  new_x="LMARGIN", new_y="NEXT")
        self.ln(8)

    def heading(self, text):
        self.set_font("CN", size=14)
        self.set_text_color(30, 60, 120)
        self.cell(0, 10, text, new_x="LMARGIN", new_y="NEXT")
        self.ln(2)

    def body(self, text):
        self.set_font("CN", size=10)
        self.set_text_color(40)
        self.multi_cell(0, 6, text, align="L")
        self.ln(2)

    def bullet(self, text):
        self.set_font("CN", size=10)
        self.set_text_color(40)
        self.cell(8, 6, "•")
        self.multi_cell(0, 6, text, align="L")
        self.ln(1)

    def numbered(self, num, text):
        self.set_font("CN", size=10)
        self.set_text_color(40)
        self.cell(12, 6, f"{num}.")
        self.multi_cell(0, 6, text, align="L")
        self.ln(1)


def save(pdf, name):
    path = os.path.join(OUTPUT_DIR, name)
    pdf.output(path)
    print(f"OK {name}")


